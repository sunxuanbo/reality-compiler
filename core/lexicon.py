# ----------------------------------------------------------------------------
# 3. 强度副词：让「非常累」和「有点累」在结算上体现不同强度
# ----------------------------------------------------------------------------
# key = 出现在文本里的副词，value = 强度倍率
INTENSIFIERS: dict[str, float] = {
    "非常": 1.5, "特别": 1.5, "超级": 1.5, "巨": 1.4, "很": 1.3,
    "太": 1.3, "好累": 1.3, "疯狂": 1.6, "一整天": 1.4, "通宵": 1.6,
    "有点": 0.7, "稍微": 0.6, "一点点": 0.5, "小小": 0.6, "偶尔": 0.7,
}


@dataclass
class MatchedEvent:
    """一次匹配的结果：事件本体 + 命中的关键词 + 本次生效的倍率。"""

    event: Event                          # 命中的事件规则
    hit_words: list[str] = field(default_factory=list)  # 实际命中的关键词，用于高亮展示
    scale: float = 1.0                    # 强度倍率，由 INTENSIFIERS 决定


def detect_scale(text: str) -> float:
    """扫描整句话，返回全局强度倍率。

    规则：取所有命中副词里「偏离 1.0 最远」的那个，避免多个副词互相抵消。
    """
    scale = 1.0                                   # 默认倍率
    for word, factor in INTENSIFIERS.items():     # 遍历副词表
        if word in text:                          # 只要句子里出现该副词
            # abs(factor - 1) 表示这个副词有多「极端」，越极端越优先
            if abs(factor - 1.0) > abs(scale - 1.0):
                scale = factor
    return scale


def match_events(text: str, world_id: str | None = None) -> list[MatchedEvent]:
    """核心匹配函数：一句话 -> 当前世界观下命中的事件列表。

    参数:
        text: 用户输入的现实日常原文
        world_id: 世界观标识（"fantasy" / "backrooms" / ...）。None 表示不过滤（兼容旧调用）。
    返回:
        MatchedEvent 列表，按词库顺序排列；一个都没命中时返回兜底事件
    """
    lowered = text.lower()                 # 统一转小写，让 "BUG" 和 "bug" 都能命中
    scale = detect_scale(lowered)          # 先算出这句话的整体强度
    # 按世界观过滤事件池；world_id 为 None 则使用全部事件
    pool = EVENTS if world_id is None else [e for e in EVENTS if world_id in e.world_tags]
    matched: list[MatchedEvent] = []       # 存放最终结果

    for event in pool:                     # 按词库定义顺序逐条扫描（越具体越靠前，先命中先生效）
        hits = [kw for kw in event.keywords if kw.lower() in lowered]  # 收集命中的关键词
        if hits:                                                       # 只要命中至少一个
            matched.append(MatchedEvent(event=event, hit_words=hits, scale=scale))

    if not matched:                        # 一个都没命中：走兜底，保证界面永远有内容
        matched.append(MatchedEvent(event=FALLBACK_EVENT, hit_words=[], scale=scale))

    return matched
